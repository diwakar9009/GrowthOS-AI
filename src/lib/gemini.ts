/**
 * Interface for AI task generation
 */
export interface AIGenerationConfig {
  model?: string;
  systemInstruction?: string;
  useSearch?: boolean;
}

/**
 * Centralized utility for Gemini AI interactions via the backend.
 */
export class AIService {
  private static readonly COOLOFF_KEY = "growthos_ai_cooloff_v2";
  private static readonly LAST_REQ_KEY = "growthos_ai_last_req_v2";
  private static readonly DAILY_QUOTA_KEY = "growthos_ai_daily_reset";

  private static getCooloffUntil(): number {
    const val = localStorage.getItem(this.COOLOFF_KEY);
    if (!val) return 0;
    const time = Number(val);
    // If the cooloff is more than 1 hour in the past, ignore it (stale data safety)
    if (Date.now() - time > 3600000) {
      this.resetSafetyPause();
      return 0;
    }
    return time;
  }

  private static setCooloffUntil(time: number) {
    localStorage.setItem(this.COOLOFF_KEY, time.toString());
  }

  private static getLastRequestTime(): number {
    return Number(localStorage.getItem(this.LAST_REQ_KEY) || "0");
  }

  static resetSafetyPause() {
    localStorage.removeItem(this.COOLOFF_KEY);
    localStorage.removeItem(this.LAST_REQ_KEY);
  }

  private static setLastRequestTime(time: number) {
    localStorage.setItem(this.LAST_REQ_KEY, time.toString());
  }
  
  private static executionQueue: Promise<any> = Promise.resolve();

  static async generateContent(prompt: string, config: AIGenerationConfig = {}) {
    // Check daily reset
    const today = new Date().toDateString();
    const lastReset = localStorage.getItem(this.DAILY_QUOTA_KEY);
    if (lastReset !== today) {
      localStorage.setItem(this.DAILY_QUOTA_KEY, today);
      this.resetSafetyPause();
    }

    return this.executionQueue = this.executionQueue.then(async () => {
      const { 
        model = "gemini-3.5-flash", 
        systemInstruction, 
        useSearch = false 
      } = config;

      const now = Date.now();
      const cooloff = this.getCooloffUntil();
      
      if (now < cooloff) {
        const remaining = Math.ceil((cooloff - now) / 1000);
        throw new Error(`AI Limit Protect: Resuming in ${remaining}s. To save your free quota, I've paused AI across all your tabs temporarily.`);
      }

      const interval = model.includes("pro") ? 10000 : 2000; 
      const lastReq = this.getLastRequestTime();
      const timeSinceLast = now - lastReq;
      
      if (timeSinceLast < interval) {
        const waitTime = interval - timeSinceLast;
        await new Promise(resolve => setTimeout(resolve, waitTime));
      }
      
      this.setLastRequestTime(Date.now());

      try {
        const idToken = await auth.currentUser?.getIdToken();
        const headers: Record<string, string> = {
          "Content-Type": "application/json",
        };
        if (idToken) {
          headers["Authorization"] = `Bearer ${idToken}`;
        }

        const customApiKey = localStorage.getItem("growthos_user_gemini_api_key");
        if (customApiKey) {
          headers["X-User-Gemini-API-Key"] = customApiKey;
        }

        const response = await fetch("/api/ai", {
          method: "POST",
          headers,
          body: JSON.stringify({
            prompt,
            model,
            systemInstruction,
            useSearch
          }),
        });

        if (!response.ok) {
          const errorData = await response.json().catch(() => ({}));
          throw new Error(errorData.error || `Server responded with ${response.status}`);
        }

        // Handle streaming response
        const reader = response.body?.getReader();
        if (!reader) throw new Error("Response body is null");

        let accumulatedText = "";
        const decoder = new TextDecoder();
        
        while (true) {
          const { done, value } = await reader.read();
          if (done) break;
          accumulatedText += decoder.decode(value, { stream: true });
        }

        if (accumulatedText.includes("[ERROR:")) {
          const errorMatch = accumulatedText.match(/\[ERROR: (.*?)\]/);
          throw new Error(errorMatch ? errorMatch[1] : "An error occurred during AI generation stream.");
        }

        return accumulatedText || "No response generated by AI.";
      } catch (error: any) {
        console.error("AI Request failed:", error);
        
        const errorMessage = error.message || "";
        
        if (errorMessage.includes("quota") || errorMessage.includes("429") || errorMessage.includes("limit")) {
          const now = Date.now();
          this.setCooloffUntil(now + 30000); // Reduced to 30s for better UX
          throw new Error(
            "Rate Limit Exceeded: You're calling the AI too fast. I've activated a 30s 'Safety Pause' to protect your free quota."
          );
        }

        if (errorMessage.includes("504") || errorMessage.toLowerCase().includes("timeout")) {
          throw new Error("Request Timed Out: The AI research took too long. Please try again or use a simpler request.");
        }

        throw new Error(`AI Error: ${errorMessage || "Connection failed. Please check your internet or server status."}`);
      }
    });
  }
}
